/* The four skill levels, for the rules above: a cart row prints the
   level inside a longer sentence, so it cannot be looked up as a whole
   string. Anything unrecognised is handed back untouched. */
/* Product names for the rules above, looked up in the dictionary itself so
   there is only ever one Devanagari spelling of each name. */
window.CC_LANG_HI_NAME = function (name) {
  var table = window.CC_LANG_HI || {};
  var key = String(name).trim();
  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : name;
};

window.CC_LANG_HI_LEVEL = function (level) {
  var map = {
    "Beginner": "बिगिनर",
    "Confident beginner": "कॉन्फ़िडेंट बिगिनर",
    "Intermediate": "इंटरमीडिएट",
    "Advanced": "एडवांस्ड"
  };
  return map[String(level).trim()] || level;
};
